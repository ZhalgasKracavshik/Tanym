/** Проверка типографики формул: npm run test:math */

import { pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (path) => import(pathToFileURL(join(root, path)).href);

const { formatMath, isFormula } = await load('src/lib/mathText.ts');

const problems = [];

/* Степень и индекс показываем маркерами — так видно, что это правда
   надстрочный узел, а не похожий на него символ в строке. */
const render = (input) =>
  formatMath(input)
    .map((part) =>
      part.kind === 'sup' ? `^{${part.text}}` : part.kind === 'sub' ? `_{${part.text}}` : part.text,
    )
    .join('');

const eq = (input, expected) => {
  const actual = render(input);
  if (actual !== expected) problems.push(`${JSON.stringify(input)}\n      получено: ${JSON.stringify(actual)}\n      ожидалось: ${JSON.stringify(expected)}`);
};

/* Тот самый случай со скриншота: варианты ответа различались одним
   символом посреди сплошной строки. */
eq('a^2+b^2=c^2', 'a^{2} + b^{2} = c^{2}');
eq('a^3-b^3=c^3', 'a^{3} \u2212 b^{3} = c^{3}');
eq('a^2-b^2=c^2', 'a^{2} \u2212 b^{2} = c^{2}');

/* Умножение звёздочкой — знак умножения. */
eq('7 * 4 - 4 = 24', '7 \u00b7 4 \u2212 4 = 24');

/* Нижние индексы у переменных. */
eq('x1 + x2', 'x_{1} + x_{2}');
eq('x1^2', 'x_{1}^{2}');

/* Разнобой в данных: ускорение записано двумя способами — на экране
   он не должен быть заметен. */
if (render('12 м/с^2') !== render('12 м/с\u00b2')) {
  problems.push('м/с^2 и м/с² должны выглядеть одинаково');
}
eq('12 м/с^2', '12 м/с^{2}');

/* «Корень из» перед формулой — знак; перед словом — по-прежнему слово. */
eq('(-b + корень из D) / (2a)', '(−b + \u221aD) / (2a)');
eq('найдём корень из дискриминанта', 'найдём корень из дискриминанта');

/* Неравенства. */
eq('x >= 5', 'x \u2265 5');
eq('x <= 5', 'x \u2264 5');

/* Проза не должна пострадать: буква с цифрой внутри слова — не индекс. */
eq('GPT4 и Python3', 'GPT4 и Python3');
eq('Ответ: 245.', 'Ответ: 245.');

/* Проза с формулой внутри: знаки не растаскиваются пробелами, но
   умножение и степень всё равно читаются. */
eq('Проверка: 2 * (-2)^2 = 8', 'Проверка: 2 \u00b7 (−2)^{2} = 8');

/* Минус одинаков в формуле и в прозе — иначе на одном экране два разных
   знака для одного действия. */
eq('Переносим -9 вправо: 3x = 22 - 7', 'Переносим \u22129 вправо: 3x = 22 \u2212 7');
eq('5x - 3x = 4 + 10', '5x \u2212 3x = 4 + 10');
eq('(-3)^2 = 9', '(\u22123)^{2} = 9');

/* ...но дефис внутри слова остаётся дефисом. */
eq('пишите на e-mail', 'пишите на e-mail');
eq('всё по-прежнему верно', 'всё по-прежнему верно');


/* Степень перед закрывающей скобкой не должна съедать саму скобку.
   Ошибка была найдена на живом контенте: выражение выводилось без
   закрывающей скобки, то есть с другим смыслом. */
eq('(2^3 * 2^4) / 2^5', '(2^{3} \u00b7 2^{4}) / 2^{5}');
eq('Вычислите (2^3 * 2^4) / 2^5.', 'Вычислите (2^{3} \u00b7 2^{4}) / 2^{5}.');
eq('(a + b)^2 + 1', '(a + b)^{2} + 1');

/* Запись показателя в скобках по-прежнему понимается. */
eq('x^(2) + 1', 'x^{2} + 1');
eq('x^(-3)', 'x^{\u22123}');

/* Признак «строка — формула целиком». */
if (!isFormula('a^2+b^2=c^2')) problems.push('a^2+b^2=c^2 должно считаться формулой');
if (isFormula('Проверка: слева 7 * 4')) problems.push('текст с кириллицей не формула');
if (isFormula('')) problems.push('пустая строка не формула');

if (problems.length > 0) {
  console.error('\u2717 Типографика формул сломана:');
  for (const problem of problems) console.error('  - ' + problem);
  process.exit(1);
}

console.log('\u2713 формулы: степени, индексы, знак умножения, корень, неравенства');
