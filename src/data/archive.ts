/** Материал по идентификатору. */
export function getMaterial(id: string | undefined): ArchiveMaterial | null {
  if (!id) return null;
  return ARCHIVE.find((material) => material.id === id) ?? null;
}

/** Задание архива по идентификатору. */
export function getArchiveTask(id: string | undefined) {
  if (!id) return null;
  for (const material of ARCHIVE) {
    const task = material.tasks.find((item) => item.id === id);
    if (task) return task;
  }
  return null;
}
