/**
 * Имя объекта в хранилище, собранное из имени файла.
 *
 * Раньше имя файла подставлялось в ключ как есть: `${id}/${время}-${имя}`.
 * Supabase Storage принимает в ключе ограниченный набор символов, и файл
 * «taným (1).pdf» или «Алгебра 7 класс.pdf» получал в ответ 400 —
 * загрузка не начиналась вовсе.
 *
 * Заметить это было тяжело: форма показывала «проверьте название и дату»,
 * то есть винила поля, которые заполнены правильно. Отказ приходил от
 * хранилища, а сообщение было про форму.
 *
 * Кириллица в именах — не исключение, а норма для учителя, который
 * выкладывает в архив «Контрольная работа №2.docx». Поэтому чинится не
 * один экран, а общее место для всех трёх загрузок.
 *
 * Исходное имя в ключ не переносится целиком: оно нужно человеку, а не
 * хранилищу, и хранится в базе отдельной колонкой там, где показывается.
 * В ключе остаётся только читаемый хвост — чтобы файл можно было опознать
 * в списке бакета, не открывая базу.
 */
export function storageObjectName(fileName: string): string {
  const dot = fileName.lastIndexOf('.');

  // Расширение важно: по нему браузер решает, показать файл или скачать.
  const extension =
    dot > 0
      ? fileName
          .slice(dot + 1)
          .toLowerCase()
          .replace(/[^a-z0-9]/g, '')
          .slice(0, 8)
      : '';

  /*
    \w без флага u — это [A-Za-z0-9_]: всё остальное, включая кириллицу,
    пробелы и скобки, схлопывается в дефис. Так задумано: ключ обязан
    состоять из символов, которые хранилище точно примет.
  */
  const stem = (dot > 0 ? fileName.slice(0, dot) : fileName)
    .replace(/[^\w-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase()
    .slice(0, 40);

  // Время и случайное число — чтобы два одинаковых имени не затирали друг
  // друга: у файлов, названных «скан.pdf», это происходило бы постоянно.
  const unique = `${Date.now()}-${Math.round(Math.random() * 1e6)}`;
  const tail = stem === '' ? unique : `${unique}-${stem}`;

  return extension === '' ? tail : `${tail}.${extension}`;
}
