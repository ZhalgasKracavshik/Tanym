/**
 * Состав пилота: какие разделы открыты первой аудитории.
 *
 * Пилот собирается вокруг афиши олимпиад и конкурсов. Остальное либо ещё
 * не нужно (объявления школы — без школы-партнёра их некому писать), либо
 * пусто (внешних центров пока нет), либо дорого и не доказано (AI-чат:
 * у школьника уже есть ChatGPT и Gemini, а квота и поверхность атаки — наши).
 *
 * Почему закрытие в proxy, а не только в меню. Спрятанная ссылка — не
 * запрет: страницу по прямому адресу всё равно отдадут, а API ответит.
 * Здесь один список, который читают и proxy (404 на сервере), и меню
 * (чтобы не показывать ссылку в никуда). Код разделов не удалён — вернуть
 * раздел значит убрать его префикс отсюда.
 *
 * Модуль без зависимостей: его импортирует proxy, а тот не должен тянуть
 * за собой клиентский код.
 */

export const DISABLED_PREFIXES: readonly string[] = [
  // Объявления школы.
  '/announcements',
  // Внешние учебные центры: кабинет, лендинг и отдельная регистрация.
  '/center',
  '/for-centers',
  '/register/center',
  // AI-наставник (свободный чат). Сократический диалог архива не здесь:
  // на нём держится проверка ответов в архиве, и без модели он отвечает
  // детерминированно — см. isAiLive ниже.
  '/chat',
  '/api/ai/chat',
  // AI-обучение целиком: диагностика, персональный план, задания по темам
  // и панель учителя с картой класса (она строится по этим заданиям).
  // Архив материалов остаётся — см. /archive и /api/ai/socratic.
  '/diagnostics',
  '/plan',
  '/learn',
  '/teacher',
  '/api/ai/feedback',
  '/api/ai/plan',
  '/api/diagnostics',
  '/api/topics',
  '/api/sync',
  // Достижения и рейтинг: текущая логика (баллы за сканы грамот и общий
  // рейтинг) снята; новая описана в docs/achievements-and-progress.md.
  '/achievements',
  '/leaderboard',
];

/**
 * Учебный модуль (диагностика, план, задания) включён ли. Пока он выключен,
 * не нужна и фоновая синхронизация прогресса (ProgressSync).
 */
export const LEARNING_ENABLED = !isDisabledPathStatic('/learn');

function isDisabledPathStatic(pathname: string): boolean {
  return DISABLED_PREFIXES.some((prefix) => pathname === prefix || pathname.startsWith(`${prefix}/`));
}

/**
 * Живая модель (Gemini) для разбора ответа и объяснения плана.
 *
 * В пилоте выключена: разбор, план и диалог по архиву отдают
 * детерминированный ответ (lib/ai/fallback.ts и ветки «без ключа» в роутах),
 * который уже показывается с пометкой «Разбор без AI».
 * Задания, диагностика, план и баллы от этого не меняются — решает движок,
 * модель только пересказывала его вывод. Включить: AI_LIVE=true в окружении.
 */
export function isAiLive(): boolean {
  return process.env.AI_LIVE === 'true';
}

export function isDisabledPath(pathname: string): boolean {
  return isDisabledPathStatic(pathname);
}
