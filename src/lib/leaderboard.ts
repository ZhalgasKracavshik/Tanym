/**
 * Школьный рейтинг и режим анонимности.
 *
 * Соревнование мотивирует не всех одинаково: часть учеников оно подстёгивает,
 * а часть — заставляет вообще не начинать, лишь бы не оказаться в конце
 * публичного списка. Поэтому здесь есть псевдонимы: имя можно скрыть, но очки
 * продолжают считаться, и из рейтинга ученик не выпадает. Это разные вещи —
 * «не хочу светиться» и «не хочу участвовать».
 */

import type { Grade, Language } from './types';

export interface LeaderboardEntry {
  id: string;
  name: string;
  grade: Grade;
  points: number;
  /** Сколько тем ученик довёл до уровня «освоено». */
  topicsMastered: number;
  /** Серия дней подряд с занятиями. */
  streak: number;
  /** true — это строка текущего пользователя, её выделяем на странице. */
  isCurrentUser?: boolean;
  /** true — вместо имени показываем псевдоним. */
  anonymous?: boolean;
}

/**
 * Животные для псевдонимов.
 *
 * Подпись хранится целиком, а не собирается из «Анонимный» + существительное:
 * в русском прилагательное согласуется по роду («Анонимный Барс», но
 * «Анонимная Рысь»), и склейка дала бы неграмотный текст.
 */
const ANONYMOUS_ANIMALS: Record<Language, string>[] = [
  { ru: 'Анонимный Барс', kk: 'Жасырын Барыс', en: 'Anonymous Snow Leopard' },
  { ru: 'Анонимный Тигр', kk: 'Жасырын Жолбарыс', en: 'Anonymous Tiger' },
  { ru: 'Анонимный Орёл', kk: 'Жасырын Қыран', en: 'Anonymous Eagle' },
  { ru: 'Анонимный Волк', kk: 'Жасырын Қасқыр', en: 'Anonymous Wolf' },
  { ru: 'Анонимный Сокол', kk: 'Жасырын Сұңқар', en: 'Anonymous Falcon' },
  { ru: 'Анонимный Лис', kk: 'Жасырын Түлкі', en: 'Anonymous Fox' },
  { ru: 'Анонимный Беркут', kk: 'Жасырын Бүркіт', en: 'Anonymous Golden Eagle' },
  { ru: 'Анонимная Рысь', kk: 'Жасырын Сілеусін', en: 'Anonymous Lynx' },
];

/**
 * Псевдоним по идентификатору ученика.
 *
 * Ключевое требование — детерминированность: один и тот же seed всегда даёт
 * одно и то же животное. Math.random() здесь недопустим, иначе «Анонимный Барс»
 * превращался бы в «Анонимного Волка» при каждой перерисовке таблицы, и
 * одноклассники не смогли бы даже узнавать друг друга по псевдониму.
 *
 * Хеш намеренно простейший (полиномиальный по кодам символов): это подпись
 * в интерфейсе, а не защита — угадать автора псевдонима всё равно можно по
 * количеству очков, и обещать здесь криптографическую стойкость было бы обманом.
 */
export function pseudonym(seed: string, language: Language): string {
  let hash = 0;
  for (let i = 0; i < seed.length; i += 1) {
    // Остаток берём на каждом шаге, чтобы не выйти за пределы точности number.
    hash = (hash * 31 + seed.charCodeAt(i)) % 1_000_000_007;
  }

  const animal = ANONYMOUS_ANIMALS[hash % ANONYMOUS_ANIMALS.length];
  return animal[language];
}

/**
 * Сортирует участников по очкам и проставляет место.
 *
 * Ранжирование стандартное соревновательное: при равных очках место одинаковое,
 * а следующее — пропускается (1, 2, 2, 4). Так честнее, чем произвольно решать,
 * кто из двух учеников с одинаковым результатом «выше».
 *
 * Порядок внутри одинаковых очков остаётся исходным: сортировка в JS стабильна,
 * а данные фиксированные — значит, таблица не будет прыгать между рендерами.
 */
export function rankEntries(entries: LeaderboardEntry[]): (LeaderboardEntry & { rank: number })[] {
  const sorted = [...entries].sort((a, b) => b.points - a.points);

  let previousPoints: number | null = null;
  let currentRank = 0;

  return sorted.map((entry, index) => {
    if (previousPoints === null || entry.points !== previousPoints) {
      currentRank = index + 1;
      previousPoints = entry.points;
    }
    return { ...entry, rank: currentRank };
  });
}

