/**
 * Типографика математики в тексте заданий.
 *
 * Зачем. В данных формулы записаны в «плоской» нотации, пригодной для
 * ввода, но не для чтения: `a^2+b^2=c^2`, `7 * 4 - 4 = 24`, `x1 + x2`,
 * `(-b + корень из D) / (2a)`. На экране это выводилось как есть, и в
 * вариантах ответа получалась стена символов, в которую нужно
 * вглядываться, чтобы отличить `a^2-b^2=c^2` от `a^2+b^2=c^2`.
 *
 * Нотация к тому же не была единообразной: ускорение записано и как
 * `м/с^2`, и как `м/с²` — в разных заданиях по-разному. После разбора
 * обе формы дают одинаковый результат, так что расхождение в данных
 * перестаёт быть заметным на экране.
 *
 * Почему свой разбор, а не KaTeX/MathJax. Во-первых, в данных нет LaTeX —
 * там обычный текст, и библиотеке всё равно пришлось бы скармливать
 * результат предварительного перевода. Во-вторых, формула здесь почти
 * всегда вкраплена в русскую прозу («Проверка: слева 7 * 4 - 4 = 24»),
 * а не стоит отдельным блоком, — то есть нужен инлайновый разбор, а не
 * вёрстка выключной формулы. В-третьих, результат — массив узлов, из
 * которых компонент строит React-элементы: строка HTML не появляется
 * нигде, и текст ученика или ответ модели не могут принести с собой
 * разметку.
 */

export type MathPart =
  | { kind: 'text'; text: string }
  | { kind: 'sup'; text: string }
  | { kind: 'sub'; text: string };

/** Юникодные степени, уже встречающиеся в данных, — к единому виду. */
const UNICODE_POWERS: Record<string, string> = {
  '\u2070': '0', '\u00b9': '1', '\u00b2': '2', '\u00b3': '3', '\u2074': '4',
  '\u2075': '5', '\u2076': '6', '\u2077': '7', '\u2078': '8', '\u2079': '9',
};

/**
 * Замены, не зависящие от контекста.
 *
 * «Корень из» разворачивается в знак только перед формулой (цифра, латинская
 * буква, скобка). Иначе фраза «найдём корень из дискриминанта» превратилась
 * бы в «найдём √дискриминанта»: слово «корень» в прозе остаётся словом.
 */
function normalize(input: string): string {
  let text = input;

  for (const [glyph, digit] of Object.entries(UNICODE_POWERS)) {
    text = text.split(glyph).join('^' + digit);
  }

  text = text.replace(/(?:квадратный\s+)?корень\s+из\s+(?=[0-9A-Za-z(])/gi, '\u221a');
  text = text.replace(/\bsqrt\s*\(/gi, '\u221a(');

  text = text.replace(/<=/g, '\u2264').replace(/>=/g, '\u2265').replace(/!=/g, '\u2260');

  /* Звёздочка в заданиях всегда означает умножение. */
  text = text.replace(/\s*\*\s*/g, ' \u00b7 ');

  return text;
}

/**
 * Строка целиком является формулой?
 *
 * Кириллица — надёжный признак прозы: в вариантах ответа вида `a^2+b^2=c^2`
 * её нет, а в объяснении «Проверка: слева ...» она есть всегда. Для чистой
 * формулы можно позволить себе то, что в прозе сломало бы текст: расставить
 * пробелы вокруг знаков и заменить дефис на настоящий минус.
 */
export function isFormula(input: string): boolean {
  const text = input.trim();
  if (text === '' || /[\u0400-\u04ff]/.test(text)) return false;
  return /[0-9]/.test(text) && /[=+\-*/^<>\u2264\u2265\u2260\u221a]/.test(text);
}

/**
 * Пробелы вокруг знаков — только для формулы целиком.
 *
 * Без этого `a^2+b^2=c^2` остаётся сплошным: глазу не за что зацепиться,
 * и варианты ответа различаются одним символом в середине строки.
 * Дефис становится минусом только между операндами: в `-2` он унарный и
 * прижат к числу, а в `a - b` — знак действия.
 */
function spaceOutFormula(text: string): string {
  let out = text.replace(/\s*([=+<>\u2264\u2265\u2260])\s*/g, ' $1 ');
  out = out.replace(/(?<=[0-9A-Za-z)\]])\s*-\s*/g, ' \u2212 ');
  out = out.replace(/(?<=[(\s]|^)-(?=[0-9A-Za-z(])/g, '\u2212');
  out = out.replace(/\s*\/\s*/g, ' / ');
  return out.replace(/\s{2,}/g, ' ').trim();
}

/*
  Минус в прозе.

  В варианте ответа `x = -3` дефис уже стал настоящим минусом, и оставить
  рядом, в объяснении к тому же заданию, ASCII-дефис — значит показать
  два разных знака для одного действия на одном экране.

  Правила намеренно узкие. У бинарного минуса обязательны пробелы с обеих
  сторон, поэтому `e-mail` остаётся словом; кириллица не входит в границы
  вовсе, так что дефис в «по-прежнему» не превратится в знак действия.
*/
function proseMinus(text: string): string {
  return text
    .replace(/(?<=[\dA-Za-z)\]])\s+-\s+(?=[\dA-Za-z(])/g, ' \u2212 ')
    .replace(/(?<=[\s(=])-(?=[\dA-Za-z(])/g, '\u2212');
}

/*
  Степень и нижний индекс.

  Индекс — одиночная латинская буква с цифрами (`x1`, `R2`, `a10`), и
  «одиночная» здесь существенна: проверки по краям не дают превратить
  `GPT4` или `Python3` в букву с индексом, потому что цифре там
  предшествует часть слова, а не отдельная переменная.
*/
/*
  Скобки вокруг показателя разбираются только парой.

  Раньше обе скобки были помечены необязательными, и запись 2^4), то есть
  степень перед закрывающей скобкой выражения, теряла эту скобку: разбор
  принимал её за вторую половину записи вида 2^(4). Выражение
  (2^3 * 2^4) / 2^5 выводилось на экран без закрывающей скобки, то есть
  с другим смыслом.

  Минус в показателе принимается в обоих видах: к моменту разбора
  расстановка знаков уже могла заменить дефис настоящим минусом.
*/
const PART_RE = /\^\(([-\u2212]?\d+)\)|\^([-\u2212]?\d+)|(?<![\p{L}\d_])([A-Za-z])(\d+)(?![\p{L}\d])/gu;

export function formatMath(input: string): MathPart[] {
  const pure = isFormula(input);
  const text = pure ? spaceOutFormula(normalize(input)) : proseMinus(normalize(input));

  const parts: MathPart[] = [];
  let last = 0;

  for (const match of text.matchAll(PART_RE)) {
    const start = match.index ?? 0;
    if (start > last) parts.push({ kind: 'text', text: text.slice(last, start) });

    /* Показатель приходит либо из записи со скобками, либо без них. */
    const power = match[1] ?? match[2];
    if (power !== undefined) {
      parts.push({ kind: 'sup', text: power.replace('-', '\u2212') });
    } else {
      parts.push({ kind: 'text', text: match[3] });
      parts.push({ kind: 'sub', text: match[4] });
    }
    last = start + match[0].length;
  }

  if (last < text.length) parts.push({ kind: 'text', text: text.slice(last) });
  return parts.length > 0 ? parts : [{ kind: 'text', text }];
}
