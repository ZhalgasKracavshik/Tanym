/**
 * Supabase-клиент для браузера.
 *
 * Клиент один на вкладку, и это важно, а не оптимизация ради красоты.
 *
 * Раньше каждый вызов createClient() создавал новый экземпляр, а вызовов
 * в приложении несколько десятков — в том числе прямо в теле компонентов,
 * то есть на каждый рендер. Каждый такой экземпляр заводит собственный
 * механизм обновления токена, свою подписку на возвращение вкладки и свой
 * доступ к общему хранилищу сессии. Десяток клиентов на одну вкладку
 * означает десяток параллельных проверок сессии при каждом переключении
 * окна, конкуренцию за общую блокировку хранилища и лавину повторных
 * запросов там, где нужен был один.
 *
 * Отсюда же брались и «данные пропадают, когда свернёшь вкладку»: у
 * каждого клиента свои события, и на возврате они срабатывали пачкой.
 *
 * Экземпляр держится в модульной переменной, а не в React-состоянии:
 * модуль в браузере один на всё приложение, и клиент переживает любые
 * перерисовки и переходы между страницами.
 */

import { createBrowserClient } from '@supabase/ssr';

function build() {
  return createBrowserClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
  );
}

/*
  Тип берётся от build(), а не от самой createBrowserClient: она обобщённая,
  и ReturnType от неё подставляет параметры схемы «как придётся» — тогда
  результаты всех запросов в приложении становятся any и проверка типов
  на них молча выключается.
*/
let client: ReturnType<typeof build> | null = null;

export function createClient() {
  /*
    На сервере кэшировать нельзя: там модуль общий на все запросы всех
    пользователей, и один клиент означал бы утечку чужой сессии. Этот
    файл серверным кодом не используется, но проверка стоит копейки,
    а цена ошибки — доступ к чужому аккаунту.
  */
  if (typeof window === 'undefined') return build();

  if (!client) client = build();
  return client;
}
