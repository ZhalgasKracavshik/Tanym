/**
 * Клиент, пишущий мимо политик доступа.
 *
 * Зачем он нужен. Серверные роуты ходят в базу под сессией самого
 * ученика, то есть с теми же правами, что и его браузер. Значит любое
 * разрешение на запись, которого хватает роуту, хватает и подделке из
 * консоли — с точки зрения Postgres это один и тот же клиент. Отличить
 * их можно только тем, чего у браузера нет: сервисным ключом.
 *
 * Поэтому таблицы, куда пишет только сервер (проверенные попытки,
 * результат диагностики), не имеют политики insert вовсе, а запись идёт
 * этим клиентом. Отсутствие политики — это и есть защита, а не недоделка.
 *
 * Ключа может не быть: локальная копия без секретов, превью-сборка.
 * Тогда функция возвращает null, и вызывающий сам решает, что делать.
 * Ронять ответ ученику из-за несохранённой статистики нельзя.
 *
 * Экземпляр один на процесс: он не хранит ничью сессию и обслуживает
 * разных учеников подряд.
 */

import { createClient, type SupabaseClient } from '@supabase/supabase-js';

let cached: SupabaseClient | null = null;

export function adminClient(): SupabaseClient | null {
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  if (!key || !url) return null;

  if (!cached) {
    cached = createClient(url, key, {
      auth: { persistSession: false, autoRefreshToken: false },
    });
  }
  return cached;
}
