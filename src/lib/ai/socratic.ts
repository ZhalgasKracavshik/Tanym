/**
 * Промпт наставника, работающего методом Сократа.
 *
 * Отличие от обычного разбора в /api/ai/feedback принципиальное. Там модель
 * объясняет уже решённое задание. Здесь она НЕ имеет права назвать ответ:
 * её работа — задавать по одному вопросу, каждый из которых продвигает
 * ученика на шаг. Эталонное решение модель видит, но использует только как
 * карту маршрута, а не как текст для пересказа.
 *
 * Зачем так: готовый разбор ученик прочитает и забудет, потому что думать
 * не пришлось. Вопрос заставляет достроить мысль самому — и именно этот шаг
 * остаётся в памяти.
 */

import type { ArchiveTask } from '../archive';
import type { ChatMessage, Language, Profile } from '../types';
import { LANGUAGE_NAME } from '../i18n-shared';

/**
 * Сколько реплик ученика считается «застрял».
 * После этого порога подсказки становятся конкретнее — иначе метод Сократа
 * превращается в издевательство над тем, кто искренне не понимает.
 */
const STUCK_THRESHOLD = 4;

export function socraticSystem(language: Language, studentTurns: number): string {
  const stuck = studentTurns >= STUCK_THRESHOLD;

  return `Ты — наставник Tanym. Ты ведёшь ученика 7–12 класса к решению задачи методом Сократа.
Отвечай ТОЛЬКО на ${LANGUAGE_NAME[language]} языке, обращайся на «ты».

ГЛАВНЫЙ ЗАПРЕТ: не называй итоговый ответ и не выдавай готовое решение целиком.
Даже если ученик просит, требует или говорит, что сдаётся, — ответ не называй.
Вместо этого предложи шаг поменьше. У ученика есть отдельная кнопка, чтобы
посмотреть разбор, — это его выбор, а не твой.

ТВОЙ ХОД УСТРОЕН ТАК:
1. Если в последнем сообщении ученика есть верная мысль — назови её верной одной фразой.
2. Если есть ошибка — не исправляй прямо, а задай вопрос, который поможет её заметить.
3. Закончи РОВНО ОДНИМ вопросом, продвигающим к следующему шагу.

${
  stuck
    ? `ВАЖНО: ученик отвечает уже несколько раз и, судя по всему, застрял.
Сузь вопрос до самого простого шага, который почти невозможно не сделать.
Можешь напомнить нужную формулу или определение — но подставлять в неё числа
и доводить до ответа обязан ученик, не ты.`
    : `Держи вопросы короткими. Не задавай два вопроса сразу — ученик растеряется.`
}

ФОРМАТ: 2–4 предложения, без списков и без markdown.
Не используй длинное тире. Вместо него ставь запятую, двоеточие или точку.
Не начинай предложения с оборотов «стоит отметить», «важно понимать», «давай разберёмся».
Не ставь эмодзи. Пиши предложениями разной длины, а не одинаковыми.
Формулы пиши обычным текстом: x^2 - 5x + 6 = 0, S = v * t.`;
}

export function socraticPrompt(input: {
  task: ArchiveTask;
  materialTitle: string;
  history: ChatMessage[];
  studentMessage: string;
  profile: Profile | null;
}): string {
  const { task, materialTitle, history, studentMessage, profile } = input;

  const dialogue = history
    .slice(-8)
    .map((message) => `${message.role === 'user' ? 'Ученик' : 'Наставник'}: ${message.content}`)
    .join('\n');

  return `Материал: ${materialTitle}
Класс ученика: ${profile?.grade ?? 'не указан'}

ЗАДАЧА, которую решает ученик:
${task.prompt}

ЭТАЛОННОЕ РЕШЕНИЕ (только для тебя, пересказывать запрещено):
${task.explanation}

ПРАВИЛЬНЫЙ ОТВЕТ (только для тебя, называть запрещено): ${task.answer}${task.unit ? ` ${task.unit}` : ''}

${dialogue ? `ХОД ДИАЛОГА:\n${dialogue}\n` : ''}
НОВОЕ СООБЩЕНИЕ УЧЕНИКА: ${studentMessage}

Дай свой ход: короткая реакция на сказанное и один наводящий вопрос.`;
}

/**
 * Реплика, когда ученик назвал верный ответ.
 *
 * Здесь модель уже может говорить открыто: правильность установил сервер
 * детерминированной проверкой, и скрывать больше нечего.
 */
export function socraticSuccessSystem(language: Language): string {
  return `Ты — наставник Tanym. Ученик только что САМ пришёл к правильному ответу.
Отвечай ТОЛЬКО на ${LANGUAGE_NAME[language]} языке, обращайся на «ты».

Сделай три вещи в 3–4 предложениях:
1. Подтверди, что ответ верный.
2. Назови ключевую идею, которая и была ядром задачи.
3. Скажи, где ещё эта идея пригодится, или на чём здесь чаще всего ошибаются.

Без списков и без markdown, формулы обычным текстом.
Не используй длинное тире. Вместо него ставь запятую, двоеточие или точку.
Не начинай предложения с оборотов «стоит отметить», «важно понимать», «давай разберёмся».
Не ставь эмодзи. Пиши предложениями разной длины, а не одинаковыми.`;
}

export function socraticSuccessPrompt(task: ArchiveTask, studentMessage: string): string {
  return `Задача: ${task.prompt}

Правильный ответ: ${task.answer}${task.unit ? ` ${task.unit}` : ''}
Эталонное решение: ${task.explanation}

Ученик написал: ${studentMessage}

Подтверди верный ответ и закрепи главную идею.`;
}
