/**
 * Подпись с бегущим бликом — состояние «модель думает».
 *
 * Приём требует, чтобы та же строка лежала и внутри элемента, и в
 * атрибуте data-text: видимый текст красится базовым цветом, а слой
 * ::before повторяет его из атрибута и обрезает по буквам градиент.
 *
 * Компонент существует именно ради этого дубля. Написанный руками, он
 * рано или поздно разойдётся: подпись поменяют в одном месте и забудут в
 * другом, и блик побежит по старым словам. Здесь строка приходит один
 * раз и расходится по обоим местам сама.
 */

export function ShimmerText({ children, className = '' }: { children: string; className?: string }) {
  return (
    <span className={`t-shimmer ${className}`} data-text={children}>
      {children}
    </span>
  );
}
